    private void btnChonSanPhamActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChonSanPhamActionPerformed
        // TODO add your handling code here:
// Lấy dòng được chọn trên bảng sản phẩm
        int index = tblSanPham.getSelectedRow();
        
        // Bắt lỗi nếu người dùng chưa chọn dòng nào
        if (index < 0) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một sản phẩm từ bảng trước khi ấn nút!");
            return;
        }
        
        Product product = list.get(index);
        int qty = 1;
        boolean newadd = true;
        for (BillDetails billDetail : listBillDetail) {
            if (product.getId() == billDetail.getProductID()) {
                billDetail.setQuantity(billDetail.getQuantity() + qty);
                newadd = false;
                break;
            }
        }
        if (newadd) {
            BillDetails billDetail = new BillDetails(0, product.getPrice(), qty, product.getId(), 0);
            listBillDetail.add(billDetail);
        }
        loadDataTableBillDetail();
    }//GEN-LAST:event_btnChonSanPhamActionPerformed

