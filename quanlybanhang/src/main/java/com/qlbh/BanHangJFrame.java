    public void loadDataTableSanPham() {
       String[] header = {"id", "ten", "so luong", "gia", "hinh", "loai sp"};
        list = ProductDAO.findALL();
        DefaultTableModel model = new DefaultTableModel(header, 0);
        for (Product product : list) {
            model.addRow(new Object[]{
                product.getId(),
                product.getName(),
                product.getQuantity(),
                product.getPrice(),
                product.getImage(),
                product.getCategoryID(),});
        }
        tblSanPham.setModel(model);    }

   public void loadDataTableBillDetail() {
    String[] header = {"Ma SP", "Ten san pham", "So luong", "Gia", "Thanh tien"};

    DefaultTableModel model = new DefaultTableModel(header, 0);
    for (BillDetails billDetail : listBillDetail) {
        int thanhTien = billDetail.getPrice() * billDetail.getQuantity();

        model.addRow(new Object[]{
            billDetail.getProductID(),     
            billDetail.getProductName(),   
            billDetail.getQuantity(),      
            billDetail.getPrice(),         
            thanhTien                    
        });
    }
    tblChiTiet.setModel(model);
    tongTien();
}


    public void tongTien() {
        int total = 0;
        for (BillDetails billDetail : listBillDetail) {
            total = total + (billDetail.getQuantity() * billDetail.getPrice());

        }
        txtTotal.setText(String.format("%,d", total));

    }

