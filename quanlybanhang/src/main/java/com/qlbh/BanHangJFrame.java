   User user = Auth.user;
        
        try {
            //Lấy dữ liệu hóa đơn
            String mahd = txtMaHoaDon.getText().trim();
            String sdt = txtSDT.getText().trim();
            
            // XÓA DẤU PHẨY ĐỂ TRÁNH LỖI KHI PARSE INT
            int tongTien = Integer.parseInt(txtTotal.getText().trim().replace(",", "").replace(".", ""));

            // xử lý ngày
            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate ld = LocalDate.parse(txtNgay.getText().trim(), fmt);
            java.sql.Date sqlDate = java.sql.Date.valueOf(ld);

            // Lưu vào bảng BILL 
            int rs = BillDAO.insertBill(mahd, sqlDate, tongTien, user.getId(),  bill.getCustomerID(),"HoanThanh");
            if (rs <= 0) {
                JOptionPane.showMessageDialog(this, "Lưu hóa đơn thất bại!");
                return;
            }

            // Lấy id hóa đơn vừa thêm
            int billId = BillDAO.getNewBillId();

            //  Lưu chi tiết
            DefaultTableModel model = (DefaultTableModel) tblChiTiet.getModel();

            for (int i = 0; i < model.getRowCount(); i++) {
                int productId = Integer.parseInt(model.getValueAt(i, 0).toString()); 
                int quantity = Integer.parseInt(model.getValueAt(i, 2).toString()); 
                int price = Integer.parseInt(model.getValueAt(i, 3).toString()); 

                BillDetailDAO.insert(billId, productId, quantity, price);
            }
            JOptionPane.showMessageDialog(this, "Lưu hóa đơn thành công!");

            // sinh mã mới + reset form
            generateMaHoaDon();
            btnLamMoiActionPerformed(null);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
        }
