    private void btnHuyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHuyActionPerformed
        // TODO add your handling code here:
        int row = tblHoaDon.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn hóa đơn cần hủy");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Bạn có chắc muốn HỦY hóa đơn này?",
                "Xác nhận",
                JOptionPane.YES_NO_OPTION
        );
        if (confirm != JOptionPane.YES_OPTION) return;

        int id = Integer.parseInt(tblHoaDon.getValueAt(row, 0).toString());
        int rs = BillDAO.cancel(id);

        if (rs > 0) {
            JOptionPane.showMessageDialog(this, "Hủy hóa đơn thành công");
            // load lại theo từ khóa hiện tại
            btnTimActionPerformed(null);
        } else {
            JOptionPane.showMessageDialog(this, "Hủy hóa đơn thất bại");
        }
                        
    }//GEN-LAST:event_btnHuyActionPerformed

