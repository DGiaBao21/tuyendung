 private void loadTable(List<Bill> bills) {
        String[] header = {"ID", "Mã HĐ", "Ngày", "Tổng tiền", "Trạng thái"};
        DefaultTableModel model = new DefaultTableModel(header, 0);
        for (Bill b : bills) {
            model.addRow(new Object[]{
                b.getId(),
                b.getMahd(),
                b.getCreatedDate(),
                b.getTotal(),
                b.getStatus()
            });
        }
        tblHoaDon.setModel(model);
    }
